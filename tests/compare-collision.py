#!/usr/bin/env python3
# Compares a level's collision in the mod with the hack's RAM, order included: compare-collision.py state rom collision.inc.c
import os
import re
import struct
import sys

src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ramdump.py')).read().rsplit('\nmain()', 1)[0]
g = {'__file__': __file__}
exec(src, g)
r = g['rdram'](sys.argv[1], open(sys.argv[2], 'rb').read())
text = open(sys.argv[3], errors='ignore').read()
verts = [tuple(map(int, m)) for m in re.findall(r'COL_VERTEX\(\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\)', text)]
print('mod vertices', len(verts))
blob = b''.join(struct.pack('>hhh', *v) for v in verts)
head = blob[:48]
at = r.find(head)
print('in RAM at', hex(at) if at >= 0 else None)
if at < 0:
    raise SystemExit
print('vertices identical', r[at:at + len(blob)] == blob, 'count word', struct.unpack('>h', r[at - 2:at])[0])
p = at + len(blob)
mod = []
pos = 0
for m in re.finditer(r'COL_TRI_INIT\(\s*(\w+),\s*(\d+)\)|COL_TRI(_SPECIAL)?\(\s*(\d+),\s*(\d+),\s*(\d+)(?:,\s*(\w+))?\)|COL_TRI_STOP', text):
    if m[1]:
        mod.append(('init', m[1], int(m[2])))
    elif m[4]:
        mod.append(('tri', int(m[4]), int(m[5]), int(m[6]), m[7]))
ram = []
while True:
    t = struct.unpack('>h', r[p:p + 2])[0]
    if t == 0x41:
        break
    n = struct.unpack('>h', r[p + 2:p + 4])[0]
    p += 4
    size = 8 if t in (0x0e, 0x24, 0x25, 0x27, 0x2c, 0x2d, 0x40, 0x65, 0x66, 0x67, 0x68, 0x69, 0x6a, 0x6b, 0x6c, 0x6d, 0x6e, 0x6f, 0x70, 0x71, 0x72, 0x73, 0x74, 0x75, 0x76, 0x77, 0x78, 0x79, 0x7a, 0x7b, 0x7c, 0x7d, 0x7e, 0x7f, 0x80, 0x81, 0x82, 0x83, 0x84, 0x85, 0x86, 0x87, 0x88, 0x89, 0x8a, 0x8b, 0x8c, 0x8d, 0x8e, 0x8f, 0x90, 0x91, 0x92, 0x93, 0x94, 0x95, 0x96, 0x97, 0x98, 0x99, 0x9a, 0x9b, 0x9c, 0x9d, 0x9e, 0x9f, 0xa0, 0xa1, 0xa2, 0xa3, 0xa4, 0xa5, 0xa6, 0xa7, 0xa8, 0xa9, 0xaa, 0xab, 0xac, 0xad, 0xae, 0xaf, 0xb0, 0xb1, 0xb2, 0xb3, 0xb4, 0xb5, 0xb6, 0xb7, 0xb8, 0xb9, 0xba, 0xbb, 0xbc, 0xbd, 0xbe, 0xbf, 0xc0, 0xc1, 0xc2, 0xc3, 0xc4, 0xc5, 0xc6, 0xc7, 0xc8, 0xc9, 0xca, 0xcb, 0xcc, 0xcd, 0xce, 0xcf, 0xd0, 0xd1, 0xd2, 0xd3, 0xd4, 0xd5, 0xd6, 0xd7, 0xd8, 0xd9, 0xda, 0xdb, 0xdc, 0xdd, 0xde, 0xdf, 0xe0, 0xe1, 0xe2, 0xe3, 0xe4, 0xe5, 0xe6, 0xe7, 0xe8, 0xe9, 0xea, 0xeb, 0xec, 0xed, 0xee, 0xef, 0xf0, 0xf1, 0xf2, 0xf3, 0xf4, 0xf5, 0xf6, 0xf7, 0xf8, 0xf9, 0xfa, 0xfb, 0xfc) else 6
    ram.append(('init', t, n))
    for i in range(n):
        ram.append(('tri', *struct.unpack('>hhh', r[p:p + 6])))
        p += size
mt = [m[1:4] for m in mod if m[0] == 'tri']
rt = [m[1:4] for m in ram if m[0] == 'tri']
print('tris mod', len(mt), 'ram', len(rt), 'groups mod', [m[2] for m in mod if m[0] == 'init'][:12], 'ram', [(hex(m[1]), m[2]) for m in ram if m[0] == 'init'][:12])
print('tri lists identical', mt == rt, 'same as a set', sorted(mt) == sorted(rt))
if mt != rt:
    k = next((i for i, (a, b) in enumerate(zip(mt, rt)) if a != b), min(len(mt), len(rt)))
    print('first difference at', k, mt[k:k + 3], rt[k:k + 3])
